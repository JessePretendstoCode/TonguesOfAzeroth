--[[---------------------------------------------------------------------------
    Voice lines the client already has.

    GENERATED by tools/Write-GameVoices.ps1 -- do not edit by hand.

    Every entry is a FileDataID and what that recording says. PlaySoundFile has
    accepted a FileDataID since patch 8.2, so the addon can play Blizzard's own
    recording without shipping, copying or redistributing any audio: the file
    is already on the player's disk inside their game client, and all that
    travels is the number.

    This is why these sound right where a synthesiser does not. The accent,
    the inflection and the character are the actor's, not an approximation of
    them -- no amount of tuning made a text-to-speech engine shout.

    Everything is one list, browsed the same way: pick who is speaking, pick
    what kind of line you want from them, read down it. Your own race's command
    set is in here too, filed under its own name rather than kept somewhere
    separate, because from the player's side it is the same question.

    The ids are global across products, so one table covers retail and Forever.
    A build that lacks a particular file simply fails to play it, which
    Voice.PlayGame reports rather than hides.
-----------------------------------------------------------------------------]]

