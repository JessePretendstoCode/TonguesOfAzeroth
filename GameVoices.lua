-- fileDataId -> text, for showing what a pinned line says without walking the
-- lists. Built once at load because the panel asks per row, per refresh.
GameVoices.ById = {}
-- fileDataId -> who says it.
GameVoices.SpeakerById = {}
-- How many lines the catalogue holds, for /toa voice to report.
GameVoices.COUNT = 0

-- The letter a line files under. Leading punctuation and quotes are stepped
-- over, so "...and so it begins" files under A -- which is where somebody
-- would go looking for it -- rather than under a full stop.
local function initial(text)
    local c = tostring(text):match("^[%p%s]*(%a)")
    return c and c:upper() or "#"
end

for _, char in ipairs(GameVoices.Characters) do
    char.count = 0
    for _, group in ipairs(char.groups) do
        char.count = char.count + #group.lines
        for _, entry in ipairs(group.lines) do
            GameVoices.ById[entry.id] = entry.text
            GameVoices.SpeakerById[entry.id] = char.who
            entry.initial = initial(entry.text)
        end
    end
    GameVoices.COUNT = GameVoices.COUNT + char.count
end

-- Walk every line, optionally narrowed to one speaker and/or one group. The
-- single place that knows the shape of the table, so the filters below cannot
-- disagree with each other about it.
local function each(who, group, fn)
    for _, char in ipairs(GameVoices.Characters) do
        if not who or who == "" or char.who == who then
            for _, g in ipairs(char.groups) do
                if not group or group == "" or g.name == group then
                    for _, entry in ipairs(g.lines) do
                        if fn(entry, char, g) then return end
                    end
                end
            end
        end
    end
end

-- Everyone with lines, in the order they are listed.
function GameVoices.Speakers()
    local out = {}
    for _, char in ipairs(GameVoices.Characters) do
        out[#out + 1] = { who = char.who, count = char.count }
    end
    return out
end

-- The groups one speaker has, in the order the generator put them. Asking for
-- nobody in particular merges them, so the picker can still offer "all the
-- battle cries in the game" before you have chosen a character.
function GameVoices.Groups(who)
    local out, seen = {}, {}
    for _, char in ipairs(GameVoices.Characters) do
        if not who or who == "" or char.who == who then
            for _, g in ipairs(char.groups) do
                local at = seen[g.name]
                if at then
                    out[at].count = out[at].count + #g.lines
                else
                    out[#out + 1] = { name = g.name, count = #g.lines }
                    seen[g.name] = #out
                end
            end
        end
    end
    return out
end

-- Which initials actually have lines behind them, and how many. A letter with
-- nothing under it is shown as unavailable rather than as an empty list, so
-- the strip tells you where to look instead of only answering once you click.
function GameVoices.Letters(who, group)
    local out = {}
    each(who, group, function(entry)
        out[entry.initial] = (out[entry.initial] or 0) + 1
    end)
    return out
end

-- Browsing, not searching. A catalogue this size is navigated by narrowing --
-- pick a speaker, pick a kind of line, pick a letter -- because guessing a
-- word that might appear in a line you have never read is not a way to find
-- anything. The query is an extra sieve on top, for when you do know.
function GameVoices.Filter(opts)
    opts = opts or {}
    local letter = opts.letter
    local limit = opts.limit or 5000
    local words = {}
    for w in tostring(opts.query or ""):lower():gmatch("%S+") do words[#words + 1] = w end

    local out, truncated = {}, false
    each(opts.who, opts.group, function(entry, char, g)
        local keep = (not letter or letter == "" or entry.initial == letter)
        if keep and #words > 0 then
            local hay = entry.text:lower() .. " " .. char.who:lower()
            for _, w in ipairs(words) do
                if not hay:find(w, 1, true) then keep = false break end
            end
        end
        if keep then
            out[#out + 1] = { id = entry.id, text = entry.text,
                              who = char.who, group = g.name }
            if #out >= limit then truncated = true return true end
        end
    end)
    return out, truncated
end

-- Plain words, no facets. Kept because "find me the line with this in it" is
-- still worth one call when you already know the words.
function GameVoices.Search(query, limit)
    return GameVoices.Filter{ query = query, limit = limit }
end
